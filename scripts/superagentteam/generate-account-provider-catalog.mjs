#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const aiDist = join(repoRoot, "packages", "ai", "dist");
const providersModule = pathToFileURL(join(aiDist, "providers", "all.js")).href;
const outputPath = join(
	repoRoot,
	"packages",
	"superagentteam-daemon",
	"src",
	"domains",
	"account",
	"provider-catalog.generated.ts",
);

if (!existsSync(aiDist)) {
	console.error(`missing ${aiDist}; run the pi build before generating the account provider catalog`);
	process.exit(2);
}

// Providers whose auth needs more than one env/credential; keep them visible but
// non-selectable until F030.5b adds the corresponding credential flow.
const COMPOSITE_AUTH_PROVIDERS = new Set([
	"amazon-bedrock",
	"azure",
	"google-vertex",
	"cloudflare-workers-ai",
	"cloudflare-ai-gateway",
]);

// Dynamic providers have no static built-in model catalog.
const DYNAMIC_PROVIDERS = new Set(["radius"]);

// Display-only override; not provider metadata.
const LABEL_OVERRIDES = {
	zai: "Z.AI / 智谱 GLM",
};

// Special env-key resolvers in packages/ai/src/env-api-keys.ts that are not in
// the envMap object. Keep these names in sync with that file; the generated
// catalog parity check fails when a provider disappears or gains no env name.
const SPECIAL_ENV_NAMES = {
	"github-copilot": ["COPILOT_GITHUB_TOKEN"],
	anthropic: ["ANTHROPIC_AUTH_TOKEN", "ANTHROPIC_OAUTH_TOKEN", "ANTHROPIC_API_KEY"],
};

function readEnvMap() {
	const source = readFileSync(join(repoRoot, "packages", "ai", "src", "env-api-keys.ts"), "utf8");
	const block = source.match(/const envMap:\s*Record<string,\s*string>\s*=\s*\{([\s\S]*?)\n\t\};/);
	if (!block) throw new Error("could not locate envMap in packages/ai/src/env-api-keys.ts");
	const envMap = {};
	for (const match of block[1].matchAll(/"([^"]+)":\s*"([^"]+)"/g)) envMap[match[1]] = match[2];
	return envMap;
}

function pickEnvName(envNames) {
	return envNames.find((name) => name.endsWith("_API_KEY")) ?? envNames.find((name) => name.endsWith("_TOKEN")) ?? envNames[0] ?? "";
}

const { builtinProviders, getBuiltinModels } = await import(providersModule);
const envMap = readEnvMap();
const providers = [];

for (const provider of builtinProviders()) {
	if (provider.auth?.apiKey === undefined) continue;
	const authKind = DYNAMIC_PROVIDERS.has(provider.id)
		? "dynamic"
		: COMPOSITE_AUTH_PROVIDERS.has(provider.id)
			? "composite"
			: "simple-env";
	const envNames = envMap[provider.id] !== undefined ? [envMap[provider.id]] : (SPECIAL_ENV_NAMES[provider.id] ?? []);
	const builtinModels = getBuiltinModels(provider.id).map((model) => model.id);
	const models = builtinModels.length > 0 ? builtinModels : provider.getModels().map((model) => model.id);
	providers.push({
		id: provider.id,
		label: LABEL_OVERRIDES[provider.id] ?? provider.name,
		envName: pickEnvName(envNames),
		envNames,
		supportsBaseUrl: authKind === "simple-env",
		suggestedModels: models.slice(0, 5),
		authKind,
		selectable: authKind === "simple-env",
		...(provider.getModels()[0]?.api !== undefined ? { api: provider.getModels()[0].api } : {}),
	});
}

providers.sort((left, right) => left.id.localeCompare(right.id));

const output = `// AUTO-GENERATED by scripts/superagentteam/generate-account-provider-catalog.mjs\n// Source: pi builtinProviders() + packages/ai/src/env-api-keys.ts. Do not edit manually.\nimport type { AccountProvider } from "./provider-types.ts";\n\nexport const GENERATED_ACCOUNT_PROVIDERS: readonly AccountProvider[] = ${JSON.stringify(providers, null, "\t")};\n`;

if (process.argv.includes("--check")) {
	const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
	if (current !== output) {
		console.error(
			"account provider catalog is stale; run `npm run generate:account-provider-catalog` after building pi-ai",
		);
		process.exitCode = 1;
	}
} else {
	writeFileSync(outputPath, output);
	console.log(`wrote ${outputPath} (${providers.length} providers)`);
}
